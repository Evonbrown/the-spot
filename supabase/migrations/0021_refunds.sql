-- =============================================================================
-- supabase/migrations/0021_refunds.sql   (Build step 7, Step 38b)
--
-- WHAT: Refunds (FR-06, UC-07, SDS class Refund) and REAL refunds in the
--       sales reports and the daily closeout:
--         1. payments.status may also be REFUNDED (when FULLY refunded; a
--            partly refunded payment stays PAID).
--         2. the refunds table: one row per refund (amount, reason, who,
--            when, the business day it was ISSUED). Rows are never changed
--            or deleted (a money record).
--         3. issue_refund(): the ONLY way to refund. Supervisor only, PAID
--            orders only, never more than what was paid (all refunds
--            together), a reason of 10+ characters.
--         4. the CLOSED-DAY LOCK (Step 36): no refund can be added on a
--            locked day; and the payments lock now allows ONE change on a
--            locked order day: PAID -> REFUNDED (see 4b, why).
--         5. READ rules: Supervisor and Manager read refunds; customers none
--            (decision: customers don't see refunds, not now).
--         6. the reports: "counted" = PAID or REFUNDED; refunds are taken
--            off ON THE DAY THEY'RE ISSUED (decision A), per payment type
--            and per day; net = gross - refunds. Expected cash (closeout)
--            = cash net, so it now goes down by the day's CASH refunds.
--
-- LAYER: Data layer (Supabase Postgres).
--
-- WHY "THE DAY IT'S ISSUED" (decision A)? A cash refund leaves the till
--   TODAY, so it must lower TODAY's expected cash, or today's count would be
--   short. It also means a closed day's figures never change: a refund for
--   yesterday's order is recorded today.
--
-- HOW TO RUN: Supabase SQL Editor -> paste this whole file -> Run.
--   Then run supabase/tests/0021_refunds_checks.sql block by block.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. payments.status: UNPAID -> PAID -> REFUNDED (full refunds only).
--    (status is text + CHECK, so a new value is just a wider CHECK: 0010.)
-- -----------------------------------------------------------------------------
alter table public.payments drop constraint payments_status_valid;
alter table public.payments
  add constraint payments_status_valid check (status in ('UNPAID', 'PAID', 'REFUNDED'));


-- -----------------------------------------------------------------------------
-- 2. refunds (SDS: Refund).
--    method       copied from the payment (Lynk refunds go back by Lynk,
--                 cash refunds come out of the till);
--    business_day the Jamaica day it was ISSUED (decision A). The CHECK
--                 makes sure it always matches refunded_at.
--    amount > 0, with at most 2 decimals (numeric(10, 2)).
-- -----------------------------------------------------------------------------
create table public.refunds (
  id           bigint generated by default as identity primary key,
  order_id     bigint not null references public.orders (id) on delete cascade,
  payment_id   bigint not null references public.payments (id) on delete cascade,
  method       text not null
                 constraint refunds_method_valid check (method in ('LYNK', 'CASH')),
  amount       numeric(10, 2) not null
                 constraint refunds_amount_positive check (amount > 0),
  reason       text not null
                 constraint refunds_reason_length check (char_length(btrim(reason)) between 10 and 500),
  refunded_by  uuid not null references public.profiles (id),
  refunded_at  timestamptz not null default now(),
  business_day date not null,
  constraint refunds_day_matches_time check (business_day = public.jamaica_day(refunded_at))
);

-- Quick look-ups: "this day's refunds" (reports) and "this order's refunds".
create index refunds_business_day_idx on public.refunds (business_day);
create index refunds_order_id_idx on public.refunds (order_id);

-- Read-only for logged-in users (RLS below decides WHO); writes only through
-- issue_refund() (our server).
alter table public.refunds enable row level security;
revoke all on public.refunds from anon, authenticated;
grant select on public.refunds to authenticated;

-- 5. READ rules: the Supervisor (issues them) and the Manager (reports).
create policy "Supervisor can read refunds"
  on public.refunds
  for select
  to authenticated
  using ((select public.current_user_role()) = 'supervisor');

create policy "Manager can read refunds"
  on public.refunds
  for select
  to authenticated
  using ((select public.current_user_role()) = 'manager');


-- -----------------------------------------------------------------------------
-- 4a. THE LOCK for refunds, and "never changed".
--     A refund can't be ADDED on a locked day (the day it's issued). And a
--     refund row can never be changed or deleted, by anyone: if a refund was
--     a mistake, the paper trail must stay (it can't be "un-refunded").
-- -----------------------------------------------------------------------------
create function public.enforce_refund_rules()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op <> 'INSERT' then
    raise exception 'Refunds can''t be changed or deleted.';
  end if;
  if public.is_day_locked(new.business_day) then
    raise exception 'Refund: the business day % is closed, so no refund can be added. The Manager can reopen the day.',
      new.business_day;
  end if;
  return new;
end;
$$;

revoke execute on function public.enforce_refund_rules() from public, anon, authenticated;

create trigger refunds_rules
  before insert or update or delete on public.refunds
  for each row execute function public.enforce_refund_rules();


-- -----------------------------------------------------------------------------
-- 4b. The payments lock, with ONE exception: PAID -> REFUNDED.
--     WHY? Decision A: a refund for YESTERDAY's order can be issued TODAY,
--     even if yesterday is closed. When it's a full refund, the payment
--     becomes REFUNDED. That doesn't change yesterday's figures (the reports
--     count PAID and REFUNDED the same; the refund itself counts TODAY), so
--     it's safe to allow. EVERY other change on a locked day is still
--     refused (same message as Step 36).
--     The test "everything except status and updated_at is the same":
--     to_jsonb(row) turns the row into JSON; "- 'status'" removes a key.
-- -----------------------------------------------------------------------------
create function public.enforce_day_not_locked_payments()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_created timestamptz;
begin
  select o.created_at into v_created from public.orders o where o.id = new.order_id;
  if v_created is null or not public.is_day_locked(public.jamaica_day(v_created)) then
    return new; -- the order's day is open: nothing to check
  end if;

  -- The one allowed change: a full refund (PAID -> REFUNDED, nothing else).
  if tg_op = 'UPDATE'
     and old.status = 'PAID' and new.status = 'REFUNDED'
     and (to_jsonb(new) - 'status' - 'updated_at') = (to_jsonb(old) - 'status' - 'updated_at') then
    return new;
  end if;

  raise exception 'Order %: the business day % is closed, so its % can''t change. The Manager can reopen the day.',
    new.order_id, public.jamaica_day(v_created), tg_table_name;
end;
$$;

revoke execute on function public.enforce_day_not_locked_payments() from public, anon, authenticated;

drop trigger payments_day_not_locked on public.payments;
create trigger payments_day_not_locked
  before insert or update on public.payments
  for each row execute function public.enforce_day_not_locked_payments();


-- -----------------------------------------------------------------------------
-- 3. issue_refund(order, amount, reason, expected_refunded, supervisor)
--    -> true when saved.
--    p_expected_refunded = the "refunded so far" the Supervisor SAW. If
--      another refund was added meanwhile, it returns FALSE and saves
--      nothing (the same "someone else changed it" idea as Step 26): the
--      Supervisor looks again before refunding more.
--    "for update" locks the payment row, so two refunds at the same moment
--      can't BOTH pass the "not more than paid" check.
--    to_char(..., 'FM999,999,990.00') writes 1500 as "1,500.00" for the
--      messages.
-- -----------------------------------------------------------------------------
create function public.issue_refund(
  p_order_id          bigint,
  p_amount            numeric,
  p_reason            text,
  p_expected_refunded numeric,
  p_supervisor        uuid
)
returns boolean
language plpgsql
set search_path = ''
as $$
declare
  v_reason     text := btrim(coalesce(p_reason, ''));
  v_payment_id bigint;
  v_method     text;
  v_status     text;
  v_paid       numeric;
  v_refunded   numeric;
begin
  -- UC-07: ONLY the Supervisor can refund.
  if not exists (select 1 from public.profiles p
                  where p.id = p_supervisor and p.role = 'supervisor') then
    raise exception 'Only the Supervisor can issue refunds.';
  end if;
  if char_length(v_reason) < 10 then
    raise exception 'Write the reason for the refund (at least 10 characters).';
  end if;
  if char_length(v_reason) > 500 then
    raise exception 'The reason can be at most 500 characters.';
  end if;
  if p_amount is null or p_amount <= 0 then
    raise exception 'The refund must be more than J$0.';
  end if;
  if p_amount <> round(p_amount, 2) then
    raise exception 'Use at most 2 decimals (cents).';
  end if;

  select pay.id, pay.method, pay.status, pay.amount
    into v_payment_id, v_method, v_status, v_paid
    from public.payments pay
   where pay.order_id = p_order_id
     for update;

  if not found then
    raise exception 'Order %: there is no payment for this order.', p_order_id;
  end if;
  if v_status = 'UNPAID' then
    raise exception 'Order %: this order isn''t paid, so there is nothing to refund.', p_order_id;
  end if;

  -- What was refunded before (all refunds of this payment).
  select coalesce(sum(r.amount), 0) into v_refunded
    from public.refunds r where r.payment_id = v_payment_id;

  if v_refunded <> coalesce(p_expected_refunded, -1) then
    return false; -- someone refunded meanwhile: look again
  end if;
  if v_refunded >= v_paid then
    raise exception 'Order %: this order is already fully refunded.', p_order_id;
  end if;
  if p_amount > v_paid - v_refunded then
    raise exception 'Order %: you can refund at most J$% (paid J$%, already refunded J$%).',
      p_order_id,
      to_char(v_paid - v_refunded, 'FM999,999,990.00'),
      to_char(v_paid, 'FM999,999,990.00'),
      to_char(v_refunded, 'FM999,999,990.00');
  end if;

  -- The refund (the lock trigger refuses it if TODAY is closed).
  insert into public.refunds (order_id, payment_id, method, amount, reason, refunded_by, refunded_at, business_day)
  values (p_order_id, v_payment_id, v_method, p_amount, v_reason, p_supervisor, now(), public.jamaica_day(now()));

  -- All of it refunded -> the payment becomes REFUNDED.
  if v_refunded + p_amount = v_paid then
    update public.payments set status = 'REFUNDED' where id = v_payment_id;
  end if;

  return true;
end;
$$;

revoke execute on function public.issue_refund(bigint, numeric, text, numeric, uuid) from public, anon, authenticated;
grant execute on function public.issue_refund(bigint, numeric, text, numeric, uuid) to service_role;


-- -----------------------------------------------------------------------------
-- 6a. report_orders: "counted" = payment PAID **or REFUNDED**, order not
--     cancelled / abandoned. WHY REFUNDED TOO? A fully refunded order was
--     still a sale on ITS day; the refund is taken off on the day it's
--     issued. If REFUNDED orders dropped out of gross AND their refund was
--     subtracted, the money would be taken off TWICE.
--     (Same columns as 0017, so "create or replace" works.)
-- -----------------------------------------------------------------------------
create or replace function public.report_orders(p_from timestamptz, p_to timestamptz)
returns table (
  id           bigint,
  created_at   timestamptz,
  status       public.order_status,
  fulfilment   text,
  total        numeric,
  delivery_fee numeric,
  method       text,
  pay_status   text,
  amount       numeric,
  counted      boolean
)
language sql
stable
set search_path = ''
as $$
  select o.id, o.created_at, o.status, o.fulfilment, o.total, o.delivery_fee,
         pay.method, pay.status, pay.amount,
         (pay.status in ('PAID', 'REFUNDED') and o.status not in ('CANCELLED', 'ABANDONED')) is true
    from public.orders o
    left join public.payments pay on pay.order_id = o.id
   where o.created_at >= p_from
     and o.created_at <  p_to
$$;

revoke execute on function public.report_orders(timestamptz, timestamptz) from public, anon, authenticated;


-- -----------------------------------------------------------------------------
-- 6b. report_summary: REAL refunds. Refunds ISSUED in [p_from, p_to), per
--     payment type (LYNK, CASH) and in total, of orders that count as sales.
--     Everything else as in 0017.
--     net = gross - refunds; each type's net = amount - its refunds.
--     totals_match still compares the payments side with the orders side
--     (the refunds are taken off both, so they cancel out).
-- -----------------------------------------------------------------------------
create or replace function public.report_summary(p_from timestamptz, p_to timestamptz)
returns jsonb
language sql
stable
set search_path = ''
as $$
  with
  period as (select * from public.report_orders(p_from, p_to)),
  counted as (select * from period where counted),
  -- Refunds ISSUED in the period, of orders that COUNT as sales (not
  -- cancelled / abandoned). A cancelled order that was paid by Lynk (and
  -- then refunded) was never in sales, so its refund isn't taken off either.
  period_refunds as (
    select r.method, r.amount
      from public.refunds r
      join public.orders o on o.id = r.order_id
     where r.refunded_at >= p_from and r.refunded_at < p_to
       and o.status not in ('CANCELLED', 'ABANDONED')
  ),
  by_method as (
    select m.method,
           (select count(*) from counted c where c.method = m.method)                 as transactions,
           (select coalesce(sum(c.amount), 0) from counted c where c.method = m.method) as amount,
           (select coalesce(sum(r.amount), 0) from period_refunds r where r.method = m.method) as refunds
      from (values ('LYNK'), ('CASH')) as m (method)
  ),
  totals as (
    select count(*)                       as orders,
           coalesce(sum(total), 0)        as gross_sales,
           coalesce(sum(delivery_fee), 0) as delivery_fees,
           (select coalesce(sum(amount), 0) from period_refunds) as refunds
      from counted
  )
  select jsonb_build_object(
    'orders',          t.orders,
    'gross_sales',     t.gross_sales,
    'delivery_fees',   t.delivery_fees,
    'refunds',         t.refunds,
    'net_sales',       t.gross_sales - t.refunds,
    'cancelled_count', (select count(*) from period where status = 'CANCELLED'),
    'cancelled_value', (select coalesce(sum(total), 0) from period where status = 'CANCELLED'),
    'abandoned_count', (select count(*) from period where status = 'ABANDONED'),
    'abandoned_value', (select coalesce(sum(total), 0) from period where status = 'ABANDONED'),
    'not_counted_count', (select count(*) from period
                           where not counted and status not in ('CANCELLED', 'ABANDONED')),
    'not_counted_value', (select coalesce(sum(total), 0) from period
                           where not counted and status not in ('CANCELLED', 'ABANDONED')),
    'by_method', (
      select jsonb_agg(jsonb_build_object(
               'method',       b.method,
               'transactions', b.transactions,
               'amount',       b.amount,
               'refunds',      b.refunds,
               'net',          b.amount - b.refunds,
               'percent',      coalesce(round((b.amount - b.refunds) * 100
                                 / nullif(t.gross_sales - t.refunds, 0), 1), 0)
             ) order by b.method desc) -- LYNK, then CASH
        from by_method b
    ),
    'methods_total', (select coalesce(sum(b.amount - b.refunds), 0) from by_method b),
    'totals_match',  (select coalesce(sum(b.amount - b.refunds), 0) from by_method b)
                       = (t.gross_sales - t.refunds)
  )
  from totals t
$$;

revoke execute on function public.report_summary(timestamptz, timestamptz) from public, anon, authenticated;


-- -----------------------------------------------------------------------------
-- 6c. sales_range_summary: each day's refunds (by the day they were ISSUED);
--     net = gross - refunds; the Cash and Lynk columns are NET (after that
--     type's refunds), the same as the Total line (which uses the summary's
--     per-type net). Otherwise as 0018 (per-day CTE first, then jsonb_agg).
-- -----------------------------------------------------------------------------
create or replace function public.sales_range_summary(p_start date, p_end date)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_from timestamptz;
  v_to   timestamptz;
  v_days jsonb;
begin
  -- Manager only, 1-31 days, end on/after start, no future days (0017).
  perform public.report_check_manager_range(p_start, p_end);

  v_from := public.jamaica_midnight(p_start);
  v_to   := public.jamaica_midnight(p_end + 1);

  with
  counted as (
    select r.*, (r.created_at at time zone 'America/Jamaica')::date as day
      from public.report_orders(v_from, v_to) r
     where r.counted
  ),
  days as (
    select d::date as day from generate_series(p_start, p_end, interval '1 day') as d
  ),
  -- STEP 1a: each day's sales.
  per_day as (
    select days.day,
           count(c.id)                                                 as orders,
           coalesce(sum(c.total), 0)                                   as gross_sales,
           coalesce(sum(c.amount) filter (where c.method = 'CASH'), 0) as cash,
           coalesce(sum(c.amount) filter (where c.method = 'LYNK'), 0) as lynk
      from days
      left join counted c on c.day = days.day
     group by days.day
  ),
  -- STEP 1b: each day's refunds (the day they were issued).
  day_refunds as (
    select days.day,
           coalesce(sum(r.amount), 0)                                   as refunds,
           coalesce(sum(r.amount) filter (where r.method = 'CASH'), 0)  as cash_refunds,
           coalesce(sum(r.amount) filter (where r.method = 'LYNK'), 0)  as lynk_refunds
      from days
      left join (select r.* from public.refunds r
                   join public.orders o on o.id = r.order_id
                  where o.status not in ('CANCELLED', 'ABANDONED')) r
        on r.business_day = days.day
     group by days.day
  )
  -- STEP 2: one JSON list, in date order.
  select jsonb_agg(jsonb_build_object(
           'day',         p.day,
           'orders',      p.orders,
           'gross_sales', p.gross_sales,
           'refunds',     d.refunds,
           'net_sales',   p.gross_sales - d.refunds,
           'cash',        p.cash - d.cash_refunds,
           'lynk',        p.lynk - d.lynk_refunds
         ) order by p.day)
    into v_days
    from per_day p
    join day_refunds d on d.day = p.day;

  return jsonb_build_object(
    'start', p_start,
    'end',   p_end,
    'total', public.report_summary(v_from, v_to),
    'days',  coalesce(v_days, '[]'::jsonb)
  );
end;
$$;

revoke execute on function public.sales_range_summary(date, date) from public, anon;
grant execute on function public.sales_range_summary(date, date) to authenticated;

-- 6d. Expected cash (closeout, 0019) needs NO change: it is the summary's
--     CASH net, which is now "paid cash minus the day's cash refunds".
--     Approving re-checks it, so a refund after the count means "count again".
