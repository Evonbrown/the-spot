-- =============================================================================
-- supabase/migrations/0004_customizations.sql
--
-- WHAT: Creates the "customizations" table: the extras a customer can add to a
--       food item, such as a side or an extra sauce, each with an extra cost.
--
-- LAYER: Data layer (Supabase Postgres), protected by Row Level Security (RLS).
--
-- WHY:
--   - FR-02: "Customizations (sides, extra sauces) with extra cost".
--     Total = items + customizations (+ delivery fee).
--   - Maintainability (SRS 3): the Manager must be able to change extras and
--     their prices WITHOUT code changes, so they live in a table.
--
-- CLASS DIAGRAM: Customization.
--
-- DECISIONS (see CLAUDE.md "Decisions made"):
--   - ONE shared list for ALL food items (sized items). Drinks have no extras.
--     So this table has no link to menu_items: the app offers every available
--     customization on every food item.
--   - Chosen with tick boxes, each at most once (no quantities), so there is no
--     quantity column.
--
-- HOW TO RUN: SQL Editor -> New query -> paste this whole file -> Run. ONCE.
--      Then run supabase/seed/sample_customizations.sql.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. The customizations table.
--
--    id           = auto-numbered (1, 2, 3, ...), like menu_items.
--    name         = what the customer sees, e.g. "Extra gravy".
--    kind         = 'side' or 'sauce'. The options panel groups extras under
--                   "Sides" and "Sauces". The CHECK rule refuses anything else
--                   (e.g. a typo like 'sause').
--                   WHY text + CHECK and not an enum (like user_role)? Both work.
--                   A CHECK rule is easier to change later if the client wants
--                   a new kind (e.g. 'drink'): just swap the rule.
--    extra_price  = numeric(10,2): EXACT money, never float (same reason as
--                   menu_items.price). Must be 0 or more; 0 is shown as "Free".
--    is_available = false -> greyed out in the panel and can't be ticked.
--    sort_order   = order in the panel (small first). Steps of 10 leave gaps.
-- -----------------------------------------------------------------------------
create table public.customizations (
  id           bigint generated by default as identity primary key,
  name         text not null,
  kind         text not null
                 constraint customizations_kind_valid check (kind in ('side', 'sauce')),
  extra_price  numeric(10, 2) not null
                 constraint customizations_extra_price_not_negative check (extra_price >= 0),
  is_available boolean not null default true,
  sort_order   integer not null default 0,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);


-- -----------------------------------------------------------------------------
-- 2. Keep updated_at correct automatically.
--    Reuses set_updated_at() from 0002_menu_items.sql (it was written to be
--    shared by any table with an updated_at column).
-- -----------------------------------------------------------------------------
create trigger customizations_set_updated_at
  before update on public.customizations
  for each row
  execute function public.set_updated_at();


-- -----------------------------------------------------------------------------
-- 3. Turn on Row Level Security. With no policies yet, nobody can do anything.
-- -----------------------------------------------------------------------------
alter table public.customizations enable row level security;


-- -----------------------------------------------------------------------------
-- 4. Table permissions ("grants"): the same pattern as menu_items.
--    - Everyone may SELECT (read): extras are part of the public menu.
--    - Logged-in users may TRY insert/update/delete; the RLS policies below only
--      let the request succeed if their role is 'manager'.
-- -----------------------------------------------------------------------------
revoke all on public.customizations from anon, authenticated;
grant select on public.customizations to anon, authenticated;
grant insert, update, delete on public.customizations to authenticated;


-- -----------------------------------------------------------------------------
-- 5. RLS policies: WHICH ROWS each user may touch.
--    Reuses current_user_role() from 0002 ("what role is the person asking?").
-- -----------------------------------------------------------------------------

-- FR-02: anyone (logged in or not) can read every extra.
-- Unavailable extras are still returned, so the panel can show them greyed out.
create policy "Anyone can read customizations"
  on public.customizations
  for select
  to anon, authenticated
  using (true);

-- Maintainability (SRS 3): only the Manager edits extras and their prices.
create policy "Managers can add customizations"
  on public.customizations
  for insert
  to authenticated
  with check ((select public.current_user_role()) = 'manager');

create policy "Managers can update customizations"
  on public.customizations
  for update
  to authenticated
  using ((select public.current_user_role()) = 'manager')
  with check ((select public.current_user_role()) = 'manager');

create policy "Managers can delete customizations"
  on public.customizations
  for delete
  to authenticated
  using ((select public.current_user_role()) = 'manager');
