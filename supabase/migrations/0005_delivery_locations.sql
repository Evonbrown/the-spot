-- =============================================================================
-- supabase/migrations/0005_delivery_locations.sql
--
-- WHAT: Creates the "delivery_locations" table: the places The Spot delivers
--       to, each with its delivery fee.
--
-- LAYER: Data layer (Supabase Postgres), protected by Row Level Security (RLS).
--
-- WHY:
--   - FR-01 / FR-04: delivery only to UWI Mona, UTech and UWI Hospital.
--   - FR-02: total = items + customizations + delivery fee (delivery only).
--   - Maintainability (SRS 3): the Manager must be able to edit delivery
--     locations (and fees) WITHOUT code changes. Until now the locations were
--     typed in src/lib/store-info.ts; now they live in this table.
--   - This table is an approved addition (not in our original suggested list).
--
-- THE SAMPLE FEE: the real delivery fee isn't known yet. Each location starts
--   with a sample fee and fee_confirmed = false, and the checkout page shows
--   "(sample, not final)" next to it. When the client gives the real fee, the
--   Manager edits delivery_fee and ticks fee_confirmed. No code change needed.
--
-- HOW TO RUN: SQL Editor -> New query -> paste this whole file -> Run. ONCE.
--      Then run supabase/seed/sample_delivery_locations.sql.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. The delivery_locations table.
--
--    id            = auto-numbered (1, 2, 3, ...). Orders will point to it (Part 19).
--    name          = e.g. 'UWI Mona'. "unique" = the same name can't be added twice.
--    delivery_fee  = numeric(10,2): EXACT money (never float), 0 or more.
--                    A fee PER location (decision), so places can differ later.
--    fee_confirmed = false -> the fee is a SAMPLE; checkout says "(sample, not final)".
--                    true  -> the client confirmed the real fee.
--    is_active     = false -> hidden at checkout (e.g. temporarily not
--                    delivering there), without deleting it, so old orders
--                    that point to it stay correct.
--    sort_order    = order in lists (small first).
-- -----------------------------------------------------------------------------
create table public.delivery_locations (
  id            bigint generated by default as identity primary key,
  name          text not null
                  constraint delivery_locations_name_unique unique,
  delivery_fee  numeric(10, 2) not null
                  constraint delivery_locations_fee_not_negative check (delivery_fee >= 0),
  fee_confirmed boolean not null default false,
  is_active     boolean not null default true,
  sort_order    integer not null default 0,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);


-- -----------------------------------------------------------------------------
-- 2. Keep updated_at correct automatically (shared function from 0002).
-- -----------------------------------------------------------------------------
create trigger delivery_locations_set_updated_at
  before update on public.delivery_locations
  for each row
  execute function public.set_updated_at();


-- -----------------------------------------------------------------------------
-- 3. Row Level Security: ON. With no policies yet, nobody can do anything.
-- -----------------------------------------------------------------------------
alter table public.delivery_locations enable row level security;


-- -----------------------------------------------------------------------------
-- 4. Grants: the same pattern as menu_items and customizations.
--    - Everyone may SELECT: the Home page lists the locations publicly.
--    - Logged-in users may TRY to change rows; RLS only lets a manager succeed.
-- -----------------------------------------------------------------------------
revoke all on public.delivery_locations from anon, authenticated;
grant select on public.delivery_locations to anon, authenticated;
grant insert, update, delete on public.delivery_locations to authenticated;


-- -----------------------------------------------------------------------------
-- 5. RLS policies. Reuses current_user_role() from 0002.
-- -----------------------------------------------------------------------------

-- Anyone can read the locations (active and inactive; the app filters).
create policy "Anyone can read delivery locations"
  on public.delivery_locations
  for select
  to anon, authenticated
  using (true);

-- Maintainability (SRS 3): only the Manager edits locations and fees.
create policy "Managers can add delivery locations"
  on public.delivery_locations
  for insert
  to authenticated
  with check ((select public.current_user_role()) = 'manager');

create policy "Managers can update delivery locations"
  on public.delivery_locations
  for update
  to authenticated
  using ((select public.current_user_role()) = 'manager')
  with check ((select public.current_user_role()) = 'manager');

create policy "Managers can delete delivery locations"
  on public.delivery_locations
  for delete
  to authenticated
  using ((select public.current_user_role()) = 'manager');
