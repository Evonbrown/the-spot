-- supabase/migrations/0013_deliveries.sql   (Build step 6, Step 31)
--
-- WHAT: Assigning delivery orders to a driver (SDS class Delivery, FR-04
--       SR-4.1 / AC-1, TS-4.1.1 / TS-4.1.2):
--         1. a "deliveries" table: ONE row per delivery order, saying WHICH
--            DeliveryPersonnel takes it, the drop-off location, and when /
--            by whom it was assigned. picked_up_at and delivered_at are
--            filled in later by the driver (Step 33, SR-4.3);
--         2. RLS: counter staff may READ deliveries and the profiles of
--            delivery staff (names for the "Assign driver" list);
--         3. assign_delivery(): the ONLY way to assign or change a driver.
--            Only our server (secret key) may run it;
--         4. a trigger: an order can't become BEING_DELIVERED without a
--            driver (nothing goes "on the road" with nobody responsible).
--
-- LAYER: Data layer (Supabase Postgres), protected by Row Level Security.
--
-- WHY A FUNCTION, NOT DIRECT WRITES? Same as status changes (0009): staff
--   can't write the table with the public key. The server action
--   (src/lib/orders/delivery-actions.ts) checks the rules and gives friendly
--   messages; this function checks them AGAIN (defence in depth) and saves.
--
-- DECISIONS: only the LATEST assignment is kept (changing the driver updates
--   the same row; no history of changes). Customers can't see deliveries yet.
--   Drivers get their own read rule in Step 32, with their screen.
--
-- HOW TO RUN: Supabase SQL Editor -> paste this whole file -> Run.
--   Then run supabase/tests/0013_deliveries_checks.sql block by block.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. The table.
--    order_id          = the order. UNIQUE: one delivery per order.
--    driver_id         = the DeliveryPersonnel taking it.
--    drop_off_location = a COPY of the location's name (e.g. "UWI Mona") when
--                        it was assigned, so this record stays true even if
--                        the Manager renames a location later.
--    assigned_at/by    = when, and which counter staff member, (last) assigned it.
--    picked_up_at      = when the driver left with it      (Step 33, empty now).
--    delivered_at      = when the driver handed it over   (Step 33, empty now).
--
--    Time rules (so Step 33 can't save nonsense): delivered needs picked up,
--    and the times can't go backwards.
-- -----------------------------------------------------------------------------
create table public.deliveries (
  id                bigint generated by default as identity primary key,
  order_id          bigint not null references public.orders (id) on delete cascade
                      constraint deliveries_one_per_order unique,
  driver_id         uuid not null references public.profiles (id),
  drop_off_location text not null,
  assigned_at       timestamptz not null default now(),
  assigned_by       uuid not null references public.profiles (id),
  picked_up_at      timestamptz,
  delivered_at      timestamptz,
  constraint deliveries_delivered_needs_picked_up
    check (delivered_at is null or picked_up_at is not null),
  constraint deliveries_picked_up_after_assigned
    check (picked_up_at is null or picked_up_at >= assigned_at),
  constraint deliveries_delivered_after_picked_up
    check (delivered_at is null or delivered_at >= picked_up_at)
);

-- "How many active deliveries does each driver have?" is asked often.
create index deliveries_driver_id_idx on public.deliveries (driver_id);


-- -----------------------------------------------------------------------------
-- 2. RLS: ON. Logged-in users may only READ, and only counter staff get a
--    policy for now. Nobody writes with the public key.
-- -----------------------------------------------------------------------------
alter table public.deliveries enable row level security;

revoke all on public.deliveries from anon, authenticated;
grant select on public.deliveries to authenticated;

create policy "Counter staff can read all deliveries"
  on public.deliveries
  for select
  to authenticated
  using ((select public.current_user_role()) = 'counter_staff');

-- Counter staff need the drivers' names (and phone, to call them) for the
-- "Assign driver" list. Only DELIVERY STAFF profiles: least privilege, as in
-- 0008. Policies add up, so the 0008 customer rule still applies too.
create policy "Counter staff can read delivery staff profiles"
  on public.profiles
  for select
  to authenticated
  using (
    (select public.current_user_role()) = 'counter_staff'
    and role = 'delivery_personnel'
  );


-- -----------------------------------------------------------------------------
-- 3. assign_delivery(): assign a driver, or change the driver.
--    p_expected_driver_id = the driver staff SAW (null = "no driver yet").
--      If it's different now, someone else just changed it: we change
--      NOTHING and return false (same idea as change_order_status, 0009).
--    Returns true when saved. Raises an error when a rule is broken.
--
--    "for update" LOCKS the order row until this transaction ends, so two
--    staff assigning at the same moment are handled one after the other
--    (the second one then sees the first one's driver and gets false).
-- -----------------------------------------------------------------------------
create function public.assign_delivery(
  p_order_id           bigint,
  p_expected_driver_id uuid,
  p_driver_id          uuid,
  p_assigned_by        uuid
)
returns boolean
language plpgsql
set search_path = ''
as $$
declare
  v_fulfilment text;
  v_status     public.order_status;
  v_location   text;
  v_current    uuid;
begin
  -- The order (locked) and its delivery location's CURRENT name.
  select o.fulfilment, o.status, dl.name
    into v_fulfilment, v_status, v_location
    from public.orders o
    left join public.delivery_locations dl on dl.id = o.delivery_location_id
   where o.id = p_order_id
     for update of o;

  if not found then
    raise exception 'Order % not found.', p_order_id;
  end if;

  -- Delivery orders only.
  if v_fulfilment <> 'DELIVERY' then
    raise exception 'Order %: only delivery orders can have a driver.', p_order_id;
  end if;

  -- Only BEFORE it leaves (and never once it is finished).
  if v_status not in ('PENDING', 'IN_PROGRESS', 'READY_FOR_PICKUP') then
    raise exception 'Order %: the driver can only be set before the order leaves (it is %).',
      p_order_id, v_status;
  end if;

  -- The driver must really be delivery staff ...
  if not exists (select 1 from public.profiles p
                  where p.id = p_driver_id and p.role = 'delivery_personnel') then
    raise exception 'That person is not a delivery staff member.';
  end if;

  -- ... and the person assigning must be counter staff (only they assign).
  if not exists (select 1 from public.profiles p
                  where p.id = p_assigned_by and p.role = 'counter_staff') then
    raise exception 'Only counter staff can assign drivers.';
  end if;

  -- Has someone else changed the driver since staff looked?
  select d.driver_id into v_current
    from public.deliveries d
   where d.order_id = p_order_id;

  if v_current is distinct from p_expected_driver_id then
    return false; -- nothing changed
  end if;

  if v_current = p_driver_id then
    raise exception 'Order %: that driver is already assigned.', p_order_id;
  end if;

  -- First assignment: add the row. Change of driver: update the SAME row
  -- (decision: latest assignment only).
  insert into public.deliveries (order_id, driver_id, drop_off_location, assigned_by)
  values (p_order_id, p_driver_id, coalesce(v_location, 'Location missing'), p_assigned_by)
  on conflict (order_id) do update
     set driver_id         = excluded.driver_id,
         drop_off_location = excluded.drop_off_location,
         assigned_at       = now(),
         assigned_by       = excluded.assigned_by;

  -- "Touch" the order (only its updated_at changes). WHY: our screens go live
  -- by listening to changes of the ORDERS table (Realtime, 0007). This makes
  -- every open staff screen (queue + details) refresh and show the new
  -- driver within seconds, without adding another Realtime table.
  update public.orders set updated_at = now() where id = p_order_id;

  return true;
end;
$$;

-- Only the server (service_role) may run it.
revoke execute on function public.assign_delivery(bigint, uuid, uuid, uuid)
  from public, anon, authenticated;
grant execute on function public.assign_delivery(bigint, uuid, uuid, uuid)
  to service_role;


-- -----------------------------------------------------------------------------
-- 4. "Being delivered needs a driver" (decision for the Step 26 button).
--    A BEFORE trigger, like the Step 28 rules: it runs before the status is
--    saved and refuses BEING_DELIVERED if the order has no delivery row.
--    It runs for everyone (server, SQL Editor), so it can't be skipped.
-- -----------------------------------------------------------------------------
create function public.enforce_driver_before_delivery()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if not exists (select 1 from public.deliveries d where d.order_id = new.id) then
    raise exception 'Order %: assign a driver before it goes out for delivery.', new.id;
  end if;
  return new;
end;
$$;

revoke execute on function public.enforce_driver_before_delivery() from public, anon, authenticated;

create trigger orders_being_delivered_needs_driver
  before update of status on public.orders
  for each row
  when (new.status = 'BEING_DELIVERED' and old.status is distinct from new.status)
  execute function public.enforce_driver_before_delivery();
