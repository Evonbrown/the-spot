-- =============================================================================
-- supabase/migrations/0012_notifications.sql   (Build step 5, Step 30)
--
-- WHAT: Customer notifications (SDS class Notification, FR-05 SR-5.4 / AC-4):
--         1. a "notifications" table: one row = one message we "sent";
--         2. a TRIGGER on orders: when an order's status changes to
--            READY_FOR_PICKUP, CANCELLED or ABANDONED, it writes exactly ONE
--            notification for that order's customer, in the SAME transaction
--            as the status change (so it can never be missed).
--
-- SIMULATED (CLAUDE.md: "SMS/email notifications (simulate or log for now)"):
--   nothing is really sent. The row records the channel, the phone/email it
--   "went to", the message text and the time, as if it had been sent. A real
--   SMS service could later read these same rows and send them.
--
-- CHANNEL (decision): SMS to the customer's phone (phone is required at
--   sign-up). Only if a profile has no phone: EMAIL to their login email.
--
-- DELIVERY ORDERS (decision): they get a notification at READY_FOR_PICKUP
--   too, but with delivery wording ("will leave with a driver soon"), so the
--   customer doesn't walk to the counter.
--
-- LAYER: Data layer (Supabase Postgres), protected by Row Level Security.
--
-- WHO CAN READ / WRITE?
--   - customers: READ their OWN notifications only (RLS);
--   - nobody can insert, change or delete them with the public key: only the
--     trigger writes them.
--
-- LIVE ON THE CUSTOMER'S PAGE: no extra Realtime needed. The notification is
--   saved in the same transaction as the status change, so when the order's
--   Realtime message arrives (0007) and the page re-reads, it's already there.
--
-- HOW TO RUN: Supabase SQL Editor -> paste this whole file -> Run.
--   Then run supabase/tests/0012_notifications_checks.sql block by block.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. The table.
--    status   = WHICH status caused it (only the three that notify).
--    channel  = 'SMS' or 'EMAIL'.
--    sent_to  = a COPY of the phone/email at that moment, so the record stays
--               true even if the customer changes their phone later.
--               null = no phone AND no email on file: nothing could be sent
--               (the row still records that we tried; staff are never blocked).
--    message  = the exact text the customer "received".
--    sent_at  = when it was "sent".
--
--    "Never twice": the unique rule on (order_id, status) = at most ONE
--    notification per order per status. (Step 28 already stops a status from
--    happening twice; this is a second lock.)
-- -----------------------------------------------------------------------------
create table public.notifications (
  id          bigint generated by default as identity primary key,
  order_id    bigint not null references public.orders (id) on delete cascade,
  customer_id uuid not null references public.profiles (id) on delete cascade,
  status      public.order_status not null
                constraint notifications_status_valid
                check (status in ('READY_FOR_PICKUP', 'CANCELLED', 'ABANDONED')),
  channel     text not null
                constraint notifications_channel_valid check (channel in ('SMS', 'EMAIL')),
  sent_to     text,
  message     text not null,
  sent_at     timestamptz not null default now(),
  constraint notifications_one_per_order_status unique (order_id, status)
);

-- Customers read "my notifications", so look-ups by customer must be fast.
create index notifications_customer_id_idx on public.notifications (customer_id);


-- -----------------------------------------------------------------------------
-- 2. Row Level Security: ON. Logged-in users may only READ (SELECT), and the
--    policy below limits that to their OWN rows. Visitors get nothing.
-- -----------------------------------------------------------------------------
alter table public.notifications enable row level security;

revoke all on public.notifications from anon, authenticated;
grant select on public.notifications to authenticated;

create policy "Customers can read their own notifications"
  on public.notifications
  for select
  to authenticated
  using (customer_id = (select auth.uid()));


-- -----------------------------------------------------------------------------
-- 3. The function the trigger runs: build the message and "send" it.
--
--    "security definer" = it runs with the rights of its OWNER (the database
--    owner), not of whoever changed the order. Why? The login email lives in
--    Supabase's own auth.users table, which normal users can't read. Nobody
--    can call this function directly (see the revoke below); only the
--    trigger runs it.
--    set search_path = '' = every table name is written in full
--    (public.…, auth.…), so nobody can trick it with a look-alike table.
-- -----------------------------------------------------------------------------
create function public.notify_customer_of_status()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_phone   text;
  v_email   text;
  v_channel text;
  v_sent_to text;
  v_message text;
begin
  -- The customer's contact details (copied into the notification).
  select nullif(btrim(p.phone), ''), u.email
    into v_phone, v_email
    from public.profiles p
    left join auth.users u on u.id = p.id
   where p.id = new.customer_id;

  -- Decision: SMS to the phone; email only if there is no phone.
  if v_phone is not null then
    v_channel := 'SMS';
    v_sent_to := v_phone;
  else
    v_channel := 'EMAIL';
    v_sent_to := v_email; -- may be null: then nothing could be sent
  end if;

  -- The message. "%s" is replaced by the Order ID (format()).
  -- Plain words, and the Order ID each time (SAF-1: staff ask for it).
  v_message := case new.status
    when 'READY_FOR_PICKUP' then
      case when new.fulfilment = 'DELIVERY'
        -- Decision: delivery wording, so they don't come to the counter.
        then format('The Spot: Order #%s is ready and will leave with a driver soon.', new.id)
        else format('The Spot: Order #%s is ready for pickup. Show your Order ID at the counter.', new.id)
      end
    when 'CANCELLED' then
      format('The Spot: Order #%s was cancelled. Questions? Please ask at the counter.', new.id)
    when 'ABANDONED' then
      format('The Spot: Order #%s was not collected, so it was marked abandoned. Questions? Please ask at the counter.', new.id)
  end;

  -- "Send" it (simulated = record it). If this order already has a
  -- notification for this status, do nothing ("never twice").
  insert into public.notifications (order_id, customer_id, status, channel, sent_to, message)
  values (new.id, new.customer_id, new.status, v_channel, v_sent_to, v_message)
  on conflict (order_id, status) do nothing;

  return null; -- an AFTER trigger's return value is ignored
end;
$$;

-- Nobody calls this directly; only the trigger below runs it.
revoke execute on function public.notify_customer_of_status() from public, anon, authenticated;


-- -----------------------------------------------------------------------------
-- 4. The trigger.
--    "after update of status" = AFTER the change is saved (so the Step 28
--    rules trigger, which runs BEFORE, has already allowed it; a refused
--    change never gets this far, so it never sends a message).
--    "when (...)" = only for the three statuses that notify, and only if the
--    status really changed. Every other status: nothing happens.
--    Same transaction as the change: if this insert failed, the status change
--    (and its history row) would be undone too. Never "ready but not told".
-- -----------------------------------------------------------------------------
create trigger orders_notify_customer
  after update of status on public.orders
  for each row
  when (
    new.status in ('READY_FOR_PICKUP', 'CANCELLED', 'ABANDONED')
    and old.status is distinct from new.status
  )
  execute function public.notify_customer_of_status();
