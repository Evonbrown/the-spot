-- =============================================================================
-- supabase/migrations/0002_menu_items.sql
--
-- WHAT: Creates the "menu_items" table: one row per item on The Spot's menu
--       (name, price, allergens, availability, ...). Also creates a small helper
--       function, current_user_role(), that RLS rules use to ask "what role is
--       the person making this request?".
--
-- LAYER: Data layer (Supabase Postgres), protected by Row Level Security (RLS).
--
-- WHY:
--   - FR-01: the menu must show prices, descriptions, daily specials and
--     allergens, and unavailable items must be greyed out.
--   - SAF-2: allergens are shown on every menu item.
--   - Maintainability (SRS 3): the Manager must be able to change items and
--     prices WITHOUT code changes. Keeping the menu in a table (instead of in a
--     code file like src/lib/sample-menu.ts) makes that possible.
--   - No stock tracking (client said food never runs out): we use is_available.
--
-- CLASS DIAGRAM: MenuItem. (The "Menu" class is simply all rows of this table.)
--
-- HOW TO RUN: Supabase dashboard -> SQL Editor -> New query -> paste this whole
--      file -> Run. Run it ONCE (running it again fails with "already exists").
--      Then run 0003_menu_item_sizes.sql, and supabase/seed/real_menu_items.sql
--      to add the menu items.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. Helper: current_user_role()
--
--    Returns the role (from our profiles table) of whoever is making the
--    request, or NULL if they are not logged in.
--
--    WHY a function? Many tables (menu_items now; orders, refunds, closeouts
--    later) need rules like "only a manager may do this". Writing the lookup
--    once means every rule asks the same question the same way.
--
--    "security definer" = the function runs with its OWNER's permissions.
--      This matters because the profiles RLS only lets a user read their own
--      row; the function reads exactly that row, but running as the owner also
--      avoids RLS rules calling RLS rules in a loop.
--    "stable" = gives the same answer for the whole query, so Postgres can work
--      it out once instead of once per row (faster).
--    "set search_path = ''" = the same safety setting as in 0001: only use the
--      exact table names we write (public.profiles).
-- -----------------------------------------------------------------------------
create function public.current_user_role()
returns public.user_role
language sql
stable
security definer
set search_path = ''
as $$
  select role from public.profiles where id = (select auth.uid());
$$;

-- Only logged-in users need to call it (the manager rules below are "to
-- authenticated"). By default Postgres lets everyone run new functions, so we
-- take that away and give it back only to logged-in users.
revoke execute on function public.current_user_role() from public, anon;
grant execute on function public.current_user_role() to authenticated;


-- -----------------------------------------------------------------------------
-- 2. The menu_items table.
--
--    id               = a whole number the database picks for us (1, 2, 3, ...).
--                       "generated by default as identity" = auto-numbering.
--    name, description = what customers read on the menu.
--    price            = numeric(10,2): an EXACT decimal number with 2 digits
--                       after the point (e.g. 1200.00), up to 99,999,999.99.
--                       WHY not "float"? Floats are approximate: 0.1 + 0.2 gives
--                       0.30000000000000004. Money must add up exactly, because
--                       FR-06 compares expected cash with counted cash.
--                       The CHECK rule refuses negative prices (0 is allowed,
--                       e.g. a free sauce).
--    category         = plain text, e.g. 'Meals', 'Sides', 'Drinks'. (Decision:
--                       text, not an enum, so the Manager can add a new
--                       category without a database change.)
--    allergens        = text[] = a LIST of text values, e.g. {Gluten,Milk}.
--                       SAF-2. An empty list {} means "no listed allergens".
--    is_available     = FR-01: false -> greyed out, cannot be added to the cart.
--    is_daily_special = FR-01: highlighted on the menu.
--    is_made_to_order = FR-01: e.g. fries. A pickup order containing one needs
--                       at least 15 minutes lead time (checked at checkout).
--    sort_order       = the order items appear in on the menu (small first).
--    created_at / updated_at = when the row was added / last changed.
-- -----------------------------------------------------------------------------
create table public.menu_items (
  id               bigint generated by default as identity primary key,
  name             text not null,
  description      text not null default '',
  price            numeric(10, 2) not null
                     constraint menu_items_price_not_negative check (price >= 0),
  category         text not null,
  allergens        text[] not null default '{}',
  is_available     boolean not null default true,
  is_daily_special boolean not null default false,
  is_made_to_order boolean not null default false,
  sort_order       integer not null default 0,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);


-- -----------------------------------------------------------------------------
-- 3. Keep updated_at correct automatically.
--
--    A trigger (see 0001) runs set_updated_at() BEFORE every UPDATE and sets
--    updated_at to the current time. WHY? So nobody (and no page) has to
--    remember to do it. Later this shows the Manager when a price last changed.
--    The function is generic, so later tables (orders, ...) can reuse it.
-- -----------------------------------------------------------------------------
create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger menu_items_set_updated_at
  before update on public.menu_items
  for each row
  execute function public.set_updated_at();


-- -----------------------------------------------------------------------------
-- 4. Turn on Row Level Security. With no policies yet, nobody can do anything.
-- -----------------------------------------------------------------------------
alter table public.menu_items enable row level security;


-- -----------------------------------------------------------------------------
-- 5. Table permissions ("grants"): WHICH ACTIONS each kind of user may try.
--    anon          = not logged in.     authenticated = logged in (any role).
--    - Everyone may SELECT (read). Decision: the menu is public; you only need
--      an account to ORDER.
--    - Logged-in users may TRY insert/update/delete, but the RLS policies below
--      only let the request succeed if their role is 'manager'.
-- -----------------------------------------------------------------------------
revoke all on public.menu_items from anon, authenticated;
grant select on public.menu_items to anon, authenticated;
grant insert, update, delete on public.menu_items to authenticated;


-- -----------------------------------------------------------------------------
-- 6. RLS policies: WHICH ROWS each user may touch.
-- -----------------------------------------------------------------------------

-- FR-01: anyone (logged in or not) can read every menu item.
-- Unavailable items are still returned so the page can show them greyed out.
create policy "Anyone can read the menu"
  on public.menu_items
  for select
  to anon, authenticated
  using (true);

-- Maintainability (SRS 3): only the Manager edits menu items and prices.
-- "(select public.current_user_role())" in a select = worked out once per query.
create policy "Managers can add menu items"
  on public.menu_items
  for insert
  to authenticated
  with check ((select public.current_user_role()) = 'manager');

create policy "Managers can update menu items"
  on public.menu_items
  for update
  to authenticated
  using ((select public.current_user_role()) = 'manager')
  with check ((select public.current_user_role()) = 'manager');

create policy "Managers can delete menu items"
  on public.menu_items
  for delete
  to authenticated
  using ((select public.current_user_role()) = 'manager');
