-- =============================================================================
-- supabase/migrations/0006_orders.sql
--
-- WHAT: Creates everything needed to STORE an order:
--         - order_status         : the 7 order statuses (an enum)
--         - orders               : one row per order (the Order ID lives here)
--         - order_items          : the items in an order
--         - order_item_customizations : the extras chosen for each item
--         - order_status_history : every status an order has had, and when
--         - payments             : how the order is paid (LYNK / CASH)
--       and the function create_order(), which saves a whole order at once.
--
-- LAYER: Data layer (Supabase Postgres), protected by Row Level Security (RLS).
--
-- WHY:
--   - FR-01: on submit, a unique numeric Order ID; the order is PENDING.
--   - FR-02: items + customizations (+ delivery fee) = total; meal notes;
--            payment method Lynk or Cash.
--   - FR-05: customers can only see THEIR OWN orders.
--   - SDS class diagram: Order, OrderItem, Customization, OrderStatus, Payment.
--
-- SECURITY DESIGN (decision, see CLAUDE.md):
--   Customers may only READ their own orders. NOBODY can insert or change
--   orders directly with the public key, because then someone could skip our
--   checkout and save an order with a price of J$0. Instead:
--     1. the placeOrder server action (Part 21) checks everything and works
--        out the prices from the database (Application layer), then
--     2. calls create_order() below, which ONLY the server can run (it uses
--        Supabase's secret "service_role" key, which never reaches a browser).
--
-- HOW TO RUN: SQL Editor -> New query -> paste this whole file -> Run. ONCE.
--      Then run supabase/tests/0006_orders_checks.sql to test it.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. The order statuses: EXACTLY the 7 names from CLAUDE.md, in their order.
--    An enum (like user_role in 0001), because these names must never change
--    and a typo like 'PENDNG' must be impossible.
--    Moving forward only (no skips, no going back) is enforced in Build step 4.
-- -----------------------------------------------------------------------------
create type public.order_status as enum (
  'PENDING',
  'IN_PROGRESS',
  'READY_FOR_PICKUP',
  'BEING_DELIVERED',
  'COMPLETED',
  'CANCELLED',
  'ABANDONED'
);


-- -----------------------------------------------------------------------------
-- 2. orders: one row per order.
--
--    id                   = the Order ID (FR-01: unique and numeric).
--                           Decision: starts at 1001, so the first order is #1001.
--    customer_id          = who ordered (their profiles row).
--    fulfilment           = 'PICKUP' or 'DELIVERY' (approved names).
--    delivery_location_id = where to deliver (delivery orders only).
--    requested_time       = when the customer wants it (Jamaica time is
--                           worked out by the app; stored as a full timestamp).
--    is_asap              = true if they chose "As soon as possible".
--    status               = starts as PENDING (FR-01).
--    items_total          = items + customizations (FR-02).
--    delivery_fee         = 0 for pickup; the location's fee for delivery.
--    total                = items_total + delivery_fee (checked below).
--    client_request_id    = a random id made once per checkout page. "unique"
--                           means the same checkout can't create two orders
--                           (double tap, or the network retrying).
--    references ...       = a "foreign key": the value must exist in that
--                           other table (e.g. a real customer, a real location).
-- -----------------------------------------------------------------------------
create table public.orders (
  id                   bigint generated by default as identity (start with 1001) primary key,
  customer_id          uuid not null references public.profiles (id),
  fulfilment           text not null
                         constraint orders_fulfilment_valid check (fulfilment in ('PICKUP', 'DELIVERY')),
  delivery_location_id bigint references public.delivery_locations (id),
  requested_time       timestamptz not null,
  is_asap              boolean not null default false,
  status               public.order_status not null default 'PENDING',
  items_total          numeric(10, 2) not null
                         constraint orders_items_total_not_negative check (items_total >= 0),
  delivery_fee         numeric(10, 2) not null default 0
                         constraint orders_delivery_fee_not_negative check (delivery_fee >= 0),
  total                numeric(10, 2) not null,
  client_request_id    uuid not null
                         constraint orders_client_request_id_unique unique,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),

  -- FR-02: total = items + customizations + delivery fee. The database refuses
  -- any order whose numbers don't add up.
  constraint orders_total_adds_up check (total = items_total + delivery_fee),

  -- FR-01/FR-04: a delivery order MUST have a location; a pickup order must
  -- NOT have one and has no delivery fee.
  constraint orders_delivery_needs_location check (
    (fulfilment = 'DELIVERY' and delivery_location_id is not null)
    or
    (fulfilment = 'PICKUP' and delivery_location_id is null and delivery_fee = 0)
  )
);

-- An "index" is like the index at the back of a book: it lets Postgres find a
-- customer's orders quickly without reading every order (PR-3: busy lunch hour).
create index orders_customer_id_idx on public.orders (customer_id);


-- -----------------------------------------------------------------------------
-- 3. order_items: the items in an order (SDS: OrderItem).
--    The name, size and prices are COPIED in at order time, so changing the
--    menu later never changes an old order (or old sales reports, FR-06).
--    "on delete cascade" = if an order were ever deleted, its items go too.
-- -----------------------------------------------------------------------------
create table public.order_items (
  id           bigint generated by default as identity primary key,
  order_id     bigint not null references public.orders (id) on delete cascade,
  menu_item_id bigint not null references public.menu_items (id),
  item_name    text not null,
  size         text
                 constraint order_items_size_valid check (size in ('Small', 'Medium', 'Large')),
  unit_price   numeric(10, 2) not null
                 constraint order_items_unit_price_not_negative check (unit_price >= 0),
  quantity     integer not null
                 constraint order_items_quantity_1_to_10 check (quantity between 1 and 10),
  note         text not null default ''
                 constraint order_items_note_max_200 check (char_length(note) <= 200),
  line_total   numeric(10, 2) not null
                 constraint order_items_line_total_not_negative check (line_total >= 0),
  created_at   timestamptz not null default now()
);

create index order_items_order_id_idx on public.order_items (order_id);


-- -----------------------------------------------------------------------------
-- 4. order_item_customizations: the extras chosen for each order item,
--    with the name and price COPIED in at order time (same reason as above).
-- -----------------------------------------------------------------------------
create table public.order_item_customizations (
  id                 bigint generated by default as identity primary key,
  order_item_id      bigint not null references public.order_items (id) on delete cascade,
  customization_id   bigint not null references public.customizations (id),
  customization_name text not null,
  extra_price        numeric(10, 2) not null
                       constraint order_item_customizations_price_not_negative check (extra_price >= 0)
);

create index order_item_customizations_item_idx on public.order_item_customizations (order_item_id);


-- -----------------------------------------------------------------------------
-- 5. order_status_history: every status an order has had, and when.
--    create_order() adds the first row (PENDING). Build step 4 adds a row on
--    every status change, so we can show "Ready at 12:21" and enforce the
--    20-minute ABANDONED rule.
--    changed_by = who made the change (the customer for PENDING, staff later).
-- -----------------------------------------------------------------------------
create table public.order_status_history (
  id         bigint generated by default as identity primary key,
  order_id   bigint not null references public.orders (id) on delete cascade,
  status     public.order_status not null,
  changed_by uuid references public.profiles (id),
  changed_at timestamptz not null default now()
);

create index order_status_history_order_id_idx on public.order_status_history (order_id);


-- -----------------------------------------------------------------------------
-- 6. payments: how an order is paid (SDS: Payment). One per order ("unique").
--    method = 'LYNK' or 'CASH' (approved names). Never card details (Security).
--    status = 'UNPAID' for now. Build step 7 adds 'PAID' and 'REFUNDED':
--      IMPORTANT: FR-06 only counts PAID orders, so cash must be marked PAID
--      when it's received, and Lynk when the Supervisor verifies it.
--    It's text + CHECK (not an enum) so step 7 can simply widen the rule.
-- -----------------------------------------------------------------------------
create table public.payments (
  id         bigint generated by default as identity primary key,
  order_id   bigint not null references public.orders (id) on delete cascade
               constraint payments_one_per_order unique,
  method     text not null
               constraint payments_method_valid check (method in ('LYNK', 'CASH')),
  amount     numeric(10, 2) not null
               constraint payments_amount_not_negative check (amount >= 0),
  status     text not null default 'UNPAID'
               constraint payments_status_valid check (status in ('UNPAID')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);


-- -----------------------------------------------------------------------------
-- 7. Keep updated_at correct automatically (shared function from 0002).
-- -----------------------------------------------------------------------------
create trigger orders_set_updated_at
  before update on public.orders
  for each row execute function public.set_updated_at();

create trigger payments_set_updated_at
  before update on public.payments
  for each row execute function public.set_updated_at();


-- -----------------------------------------------------------------------------
-- 8. Row Level Security ON for all 5 tables.
-- -----------------------------------------------------------------------------
alter table public.orders                    enable row level security;
alter table public.order_items               enable row level security;
alter table public.order_item_customizations enable row level security;
alter table public.order_status_history      enable row level security;
alter table public.payments                  enable row level security;


-- -----------------------------------------------------------------------------
-- 9. Grants: logged-in users may only SELECT (read). No insert/update/delete
--    for anyone using the public key. Visitors (anon) get nothing at all.
--    Writing happens only through create_order() (section 11), run by the server.
-- -----------------------------------------------------------------------------
revoke all on public.orders, public.order_items, public.order_item_customizations,
              public.order_status_history, public.payments
  from anon, authenticated;

grant select on public.orders, public.order_items, public.order_item_customizations,
                public.order_status_history, public.payments
  to authenticated;


-- -----------------------------------------------------------------------------
-- 10. RLS policies (FR-05): a customer can read ONLY their own orders, and the
--     items, extras, history and payment that belong to them.
--     "exists (select 1 ...)" = "is there an order with this id that belongs
--     to the person asking?". Staff rules come in Build step 4.
-- -----------------------------------------------------------------------------
create policy "Customers can read their own orders"
  on public.orders
  for select
  to authenticated
  using (customer_id = (select auth.uid()));

create policy "Customers can read items of their own orders"
  on public.order_items
  for select
  to authenticated
  using (exists (
    select 1 from public.orders o
    where o.id = order_items.order_id
      and o.customer_id = (select auth.uid())
  ));

create policy "Customers can read extras of their own orders"
  on public.order_item_customizations
  for select
  to authenticated
  using (exists (
    select 1
    from public.order_items oi
    join public.orders o on o.id = oi.order_id
    where oi.id = order_item_customizations.order_item_id
      and o.customer_id = (select auth.uid())
  ));

create policy "Customers can read the history of their own orders"
  on public.order_status_history
  for select
  to authenticated
  using (exists (
    select 1 from public.orders o
    where o.id = order_status_history.order_id
      and o.customer_id = (select auth.uid())
  ));

create policy "Customers can read the payment of their own orders"
  on public.payments
  for select
  to authenticated
  using (exists (
    select 1 from public.orders o
    where o.id = payments.order_id
      and o.customer_id = (select auth.uid())
  ));


-- -----------------------------------------------------------------------------
-- 11. create_order(): saves a WHOLE order in one transaction.
--
--     A function's body runs as one transaction: the order, its items, their
--     extras, the first status (PENDING) and the payment are ALL saved, or (if
--     anything fails) NONE of them. So there's never half an order.
--
--     WHO CAN RUN IT: only "service_role" = our server, using the secret key
--     (Part 21). Customers can't call it, so they can't invent prices.
--     The server has ALREADY checked every rule and worked out every price
--     from the database (Application layer). This function double-checks that
--     the numbers add up, as a last safety net ("defence in depth").
--
--     p_items is JSON (a list), one entry per order item:
--       { "menu_item_id": 5, "item_name": "Fry Chicken", "size": "Large",
--         "unit_price": 1200, "quantity": 2, "note": "", "line_total": 2700,
--         "extras": [ { "customization_id": 2, "customization_name": "Coleslaw (Sample)",
--                       "extra_price": 150 } ] }
--
--     RETURNS the new Order ID (e.g. 1001).
--     SAME CHECKOUT TWICE (same p_client_request_id): returns the FIRST
--     order's id instead of creating a duplicate.
-- -----------------------------------------------------------------------------
create function public.create_order(
  p_customer_id          uuid,
  p_client_request_id    uuid,
  p_fulfilment           text,
  p_delivery_location_id bigint,
  p_requested_time       timestamptz,
  p_is_asap              boolean,
  p_items_total          numeric,
  p_delivery_fee         numeric,
  p_payment_method       text,
  p_items                jsonb
)
returns bigint
language plpgsql
set search_path = ''
as $$
declare
  v_order_id      bigint;
  v_order_item_id bigint;
  v_item          jsonb;
  v_extra         jsonb;
  v_sum_lines     numeric := 0;
begin
  -- Safety net 1: an order must have at least one item.
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'An order needs at least one item.';
  end if;

  -- Safety net 2: the line totals must add up to items_total.
  select coalesce(sum((item ->> 'line_total')::numeric), 0)
    into v_sum_lines
    from jsonb_array_elements(p_items) as item;
  if v_sum_lines <> p_items_total then
    raise exception 'Line totals (%) do not add up to items_total (%).', v_sum_lines, p_items_total;
  end if;

  -- The order itself. "on conflict ... do nothing": if this checkout was
  -- already saved (same client_request_id), skip it instead of failing.
  insert into public.orders (
    customer_id, client_request_id, fulfilment, delivery_location_id,
    requested_time, is_asap, items_total, delivery_fee, total
  )
  values (
    p_customer_id, p_client_request_id, p_fulfilment, p_delivery_location_id,
    p_requested_time, p_is_asap, p_items_total, p_delivery_fee,
    p_items_total + p_delivery_fee
  )
  on conflict (client_request_id) do nothing
  returning id into v_order_id;

  -- Already saved before? Return that order's id (only if it's the same
  -- customer's, so nobody can fish for other people's order numbers).
  if v_order_id is null then
    select id into v_order_id
      from public.orders
     where client_request_id = p_client_request_id
       and customer_id = p_customer_id;
    if v_order_id is null then
      raise exception 'This checkout id was already used.';
    end if;
    return v_order_id;
  end if;

  -- Each order item, then its extras.
  for v_item in select * from jsonb_array_elements(p_items) loop
    insert into public.order_items (
      order_id, menu_item_id, item_name, size, unit_price, quantity, note, line_total
    )
    values (
      v_order_id,
      (v_item ->> 'menu_item_id')::bigint,
      v_item ->> 'item_name',
      nullif(v_item ->> 'size', ''),
      (v_item ->> 'unit_price')::numeric,
      (v_item ->> 'quantity')::integer,
      coalesce(v_item ->> 'note', ''),
      (v_item ->> 'line_total')::numeric
    )
    returning id into v_order_item_id;

    for v_extra in select * from jsonb_array_elements(coalesce(v_item -> 'extras', '[]'::jsonb)) loop
      insert into public.order_item_customizations (
        order_item_id, customization_id, customization_name, extra_price
      )
      values (
        v_order_item_id,
        (v_extra ->> 'customization_id')::bigint,
        v_extra ->> 'customization_name',
        (v_extra ->> 'extra_price')::numeric
      );
    end loop;
  end loop;

  -- FR-01: the order starts as PENDING. Record that in the history.
  insert into public.order_status_history (order_id, status, changed_by)
  values (v_order_id, 'PENDING', p_customer_id);

  -- FR-02: the payment (LYNK or CASH), UNPAID for now (see section 6).
  insert into public.payments (order_id, method, amount)
  values (v_order_id, p_payment_method, p_items_total + p_delivery_fee);

  return v_order_id;
end;
$$;

-- Only the server (service_role) may run create_order().
-- By default Postgres lets everyone run new functions, so we take that away.
revoke execute on function public.create_order(
  uuid, uuid, text, bigint, timestamptz, boolean, numeric, numeric, text, jsonb
) from public, anon, authenticated;

grant execute on function public.create_order(
  uuid, uuid, text, bigint, timestamptz, boolean, numeric, numeric, text, jsonb
) to service_role;
